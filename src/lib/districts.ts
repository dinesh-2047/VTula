/**
 * Districts for a state, or an empty list for an unknown one.
 *
 * Returning empty rather than throwing is deliberate: the caller is a form
 * that has to render something sensible before a state has been picked.
 */
export function districtsFor(state: string | null | undefined): string[] {
  if (!state) return [];
  return DISTRICTS_BY_STATE[state] ?? [];
}

/** Whether `district` is a real district of `state`. */
export function isValidDistrict(state: string, district: string): boolean {
  return districtsFor(state).includes(district);
}

/**
 * Guards against the list drifting away from `INDIAN_STATES`.
 *
 * A state present in one and absent from the other is a state whose businesses
 * cannot finish registration, which is the kind of failure that shows up only
 * when someone from that state tries. Called by the migration so it is caught
 * at deploy time instead.
 */
export function statesMissingDistricts(): string[] {
  return INDIAN_STATES.filter((s) => !DISTRICTS_BY_STATE[s]?.length);
}
